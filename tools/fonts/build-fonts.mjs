// Builds src/fonts/: the metric-compatible stand-ins for Word's common fonts (Carlito for Calibri, Caladea for
// Cambria, Arimo, Tinos and Cousine for Arial, Times New Roman and Courier New), their Latin and Latin Extended files,
// and fonts.css offering each under the name the editor's font stacks already use (ooxml/props.js SUBST). A font
// installed on the computer wins: each rule asks for the local one first.
// usage: node tools/fonts/build-fonts.mjs <folder holding the unpacked @fontsource packages> <folder with Caladea 2013 .woff2>
//   (npm pack @fontsource/carlito @fontsource/arimo @fontsource/tinos @fontsource/cousine, then untar each. Caladea: the
//   2013 release, crosextrafonts-20130214, converted with fontTools: see tools/fonts/README.md. Later Caladea releases
//   changed its widths and no longer match Cambria's.)
import fs from 'node:fs';
import path from 'node:path';

const [from, caladea] = process.argv.slice(2);
if (!from || !caladea) throw new Error('usage: node tools/fonts/build-fonts.mjs <folder with the unpacked @fontsource packages> <folder with Caladea 2013 .woff2>');
const out = path.resolve('src/fonts');
fs.mkdirSync(path.join(out, 'files'), { recursive: true });

// fontsource id -> [family name the stacks use, names it may be installed under]
const FAMILIES = {
  carlito: ['Carlito', ['Carlito']],
  arimo: ['Liberation Sans', ['Liberation Sans', 'LiberationSans', 'Arimo']],
  tinos: ['Liberation Serif', ['Liberation Serif', 'LiberationSerif', 'Tinos']],
  cousine: ['Liberation Mono', ['Liberation Mono', 'LiberationMono', 'Cousine']],
};
const SUBSETS = ['latin', 'latin-ext'];
const FACES = [['400', 'normal'], ['400', 'italic'], ['700', 'normal'], ['700', 'italic']];
const STYLE_NAME = { '400normal': 'Regular', '400italic': 'Italic', '700normal': 'Bold', '700italic': 'Bold Italic' };

const pkgDir = (id) => {
  const d = fs.readdirSync(from).find((x) => x.startsWith(`fontsource-${id}-`));
  if (!d) throw new Error(`no unpacked @fontsource/${id} in ${from}`);
  return path.join(from, d, 'package');
};

const rules = [];
const licenses = [];
for (const [id, [family, locals]] of Object.entries(FAMILIES)) {
  const dir = pkgDir(id);
  const version = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')).version;
  licenses.push(`## ${family} (from ${id[0].toUpperCase() + id.slice(1)}, @fontsource/${id} ${version})\n\n${fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8').trim()}\n`);
  for (const subset of SUBSETS) {
    // The subset's unicode-range, from fontsource's list of them.
    const range = JSON.parse(fs.readFileSync(path.join(dir, 'unicode.json'), 'utf8'))[subset];
    if (!range) throw new Error(`no ${subset} range for ${id}`);
    for (const [weight, style] of FACES) {
      const file = `${id}-${subset}-${weight}-${style}.woff2`;
      fs.copyFileSync(path.join(dir, 'files', file), path.join(out, 'files', file));
      const styled = STYLE_NAME[weight + style];
      const local = locals.flatMap((n) => [`local('${n}${styled === 'Regular' ? '' : ' ' + styled}')`, `local('${n.replace(/ /g, '')}-${styled.replace(/ /g, '')}')`]);
      rules.push(`@font-face { font-family: '${family}'; font-style: ${style}; font-weight: ${weight}; font-display: swap; src: ${local.join(', ')}, url('./files/${file}') format('woff2'); unicode-range: ${range}; }`);
    }
  }
}
// Caladea (Cambria's widths), from its 2013 release: one file per face, all its characters.
for (const [weight, style] of FACES) {
  const styled = STYLE_NAME[weight + style];
  const file = `caladea-${styled.replace(/ /g, '').toLowerCase()}.woff2`;
  fs.copyFileSync(path.join(caladea, `Caladea-${styled.replace(/ /g, '')}.woff2`), path.join(out, 'files', file));
  rules.push(`@font-face { font-family: 'Caladea'; font-style: ${style}; font-weight: ${weight}; font-display: swap; src: local('Caladea${styled === 'Regular' ? '' : ' ' + styled}'), local('Caladea-${styled.replace(/ /g, '')}'), url('./files/${file}') format('woff2'); }`);
}
const apache = fs.readFileSync(path.resolve('node_modules/typescript/LICENSE.txt'), 'utf8').trim();
licenses.push(`## Caladea (Caladea 1.002, Copyright (c) 2012 Huerta Tipografia; from Google's crosextrafonts-20130214)

Licensed under the Apache License, Version 2.0:

${apache}
`);
fs.writeFileSync(path.join(out, 'fonts.css'), `/* open-docx-editor: metric-compatible stand-ins for Word's common fonts, for computers without them.
   Import once (import 'open-docx-editor/fonts.css', or a <link> to this file beside its files/ folder). Carlito and
   Caladea have Calibri's and Cambria's widths; Liberation Sans, Serif and Mono (here from Arimo, Tinos and Cousine,
   the same designs) have Arial's, Times New Roman's and Courier New's, so lines break where Word breaks them. A font
   installed on the computer is used before the bundled file. Generated by tools/fonts/build-fonts.mjs; licenses in
   LICENSE.md (SIL Open Font License 1.1; Caladea: Apache License 2.0). */
${rules.join('\n')}
`);
fs.writeFileSync(path.join(out, 'LICENSE.md'), `# Licenses of the bundled fonts\n\nThe font files in files/ are distributed under the SIL Open Font License 1.1, except Caladea, under the Apache License\n2.0; each license is reproduced below. They are unmodified copies of the files published in the @fontsource packages\nnamed, and Caladea's of its 2013 release.\n\n${licenses.join('\n')}`);
console.log(`${rules.length} faces, ${fs.readdirSync(path.join(out, 'files')).length} files`);
