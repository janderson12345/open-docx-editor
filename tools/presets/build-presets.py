# Builds src/ooxml/presets-data.js from ECMA-376 Part 1's presetShapeDefinitions.xml (in the standard's download,
# OfficeOpenXML-DrawingMLGeometries.zip), in the compact form presets.js reads: one guide or path a line.
# usage: python tools/presets/build-presets.py <presetShapeDefinitions.xml>
import sys
import xml.etree.ElementTree as ET

A = '{http://schemas.openxmlformats.org/drawingml/2006/main}'
root = ET.parse(sys.argv[1]).getroot()


def pt(el):
    p = el.find(A + 'pt')
    return [p.get('x'), p.get('y')]


out = {}
for shape in root:
    name = shape.tag
    lines = []
    for kind in ('avLst', 'gdLst'):
        lst = shape.find(A + kind)
        if lst is None:
            continue
        for gd in lst.findall(A + 'gd'):
            lines.append(f"{'av' if kind == 'avLst' else 'gd'} {gd.get('name')} = {' '.join(gd.get('fmla').split())}")
    plst = shape.find(A + 'pathLst')
    for path in (plst if plst is not None else []):
        opts = []
        if path.get('fill') and path.get('fill') != 'norm':
            opts.append(f"fill={path.get('fill')}")
        if path.get('stroke') in ('0', 'false'):
            opts.append('stroke=0')
        if path.get('w'):
            opts.append(f"w={path.get('w')}")
        if path.get('h'):
            opts.append(f"h={path.get('h')}")
        cmds = []
        for c in path:
            tag = c.tag[len(A):]
            if tag == 'moveTo':
                cmds += ['M', *pt(c)]
            elif tag == 'lnTo':
                cmds += ['L', *pt(c)]
            elif tag == 'arcTo':
                cmds += ['A', c.get('wR'), c.get('hR'), c.get('stAng'), c.get('swAng')]
            elif tag == 'cubicBezTo':
                cmds += ['C', *[v for p in c.findall(A + 'pt') for v in (p.get('x'), p.get('y'))]]
            elif tag == 'quadBezTo':
                cmds += ['Q', *[v for p in c.findall(A + 'pt') for v in (p.get('x'), p.get('y'))]]
            elif tag == 'close':
                cmds.append('Z')
        lines.append(f"path{'(' + ', '.join(opts) + ')' if opts else ''} {' '.join(cmds)}")
    # Adjust handles (the yellow dots that drag an adjust value): ah xy|polar, then their attributes and the handle's
    # position (x=, y=), each key=value.
    alst = shape.find(A + 'ahLst')
    for ah in (alst if alst is not None else []):
        kind = {'ahXY': 'xy', 'ahPolar': 'polar'}.get(ah.tag[len(A):])
        pos = ah.find(A + 'pos')
        if kind is not None and pos is not None:
            attrs = [f'{k}={v}' for k, v in ah.attrib.items()]
            lines.append(f"ah {kind} {' '.join(attrs)} x={pos.get('x')} y={pos.get('y')}")
    out[name] = '\n'.join(lines)

# Missing from the standard's file (it has upDownArrow twice instead): upArrow, as downArrow turned upside down.
out.setdefault('upArrow', chr(10).join([
    'av adj1 = val 50000', 'av adj2 = val 50000', 'gd maxAdj2 = */ 100000 h ss', 'gd a1 = pin 0 adj1 100000', 'gd a2 = pin 0 adj2 maxAdj2',
    'gd dy1 = */ ss a2 100000', 'gd y1 = +- t dy1 0', 'gd dx1 = */ w a1 200000', 'gd x1 = +- hc 0 dx1', 'gd x2 = +- hc dx1 0',
    'gd dy2 = */ x1 dy1 wd2', 'gd y2 = +- y1 0 dy2',
    'path M l y1 L hc t L r y1 L x2 y1 L x2 b L x1 b L x1 y1 Z',
    'ah xy gdRefX=adj1 minX=0 maxX=100000 x=x1 y=b', 'ah xy gdRefY=adj2 minY=0 maxY=maxAdj2 x=l y=y1']))

js = ['// Generated by tools/presets/build-presets.py from ECMA-376 Part 1 (5th edition), presetShapeDefinitions.xml: every',
      "// DrawingML preset shape's guides and paths, one a line (presets.js reads them). Don't edit: run the script again.",
      'export const PRESET_SRC = {']
for name in sorted(out):
    body = out[name].replace('\\', '\\\\').replace('`', '\\`')
    js.append(f'  {name}: `{body}`,')
js.append('};')
open('src/ooxml/presets-data.js', 'w', encoding='utf8', newline='\n').write('\n'.join(js) + '\n')
print(len(out), 'shapes')
